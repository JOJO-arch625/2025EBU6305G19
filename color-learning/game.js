function checkNearbyStation() {
    let nextActive = null;
    let smallestDistance = Infinity;

    Object.values(stations).forEach((station) => {
        const distance = distanceToStation(station);
        if (distance <= station.radius && distance < smallestDistance) {
            nextActive = station.key;
            smallestDistance = distance;
        }
    });

    worldState.activeStationKey = nextActive;

    if (nextActive === "model") {
        tasks.modelVisit = true;
    }
    if (nextActive === "gate") {
        tasks.gateVisit = true;
    }

    updateStationPrompt();
    updateMissionProgress();
}

