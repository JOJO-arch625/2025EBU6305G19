function t(key) {
    return gameCopy[state.language][key];
}

function applyStaticTranslations() {
    document.documentElement.lang = state.language === "en" ? "en" : "zh-CN";
    document.querySelectorAll("[data-i18n]").forEach((node) => {
        node.textContent = t(node.dataset.i18n);
    });

    elements.chipsLanguage.forEach((button) => {
        button.classList.toggle("is-active", button.dataset.language === state.language);
    });

    elements.soundToggle.textContent = state.soundEnabled ? t("sound_on") : t("sound_off");
}

function setMode(nextMode) {
    state.mode = nextMode;
    elements.modeButtons.forEach((button) => {
        button.classList.toggle("is-active", button.dataset.mode === nextMode);
    });
    elements.panelModel.classList.toggle("is-visible", nextMode === "model-match");
    elements.panelHue.classList.toggle("is-visible", nextMode === "hue-lab");
}

function updateScore(statusKey) {
    elements.scorePoints.textContent = String(state.score);
    elements.scoreStreak.textContent = String(state.streak);
    elements.scoreStatus.textContent = t(statusKey);
}

function updateProgressBar(textNode, fillNode, current, total) {
    textNode.textContent = `${current} / ${total}`;
    fillNode.style.width = `${(current / total) * 100}%`;
}

function playFeedbackTone(frequency) {
    if (!state.soundEnabled) {
        return;
    }

    const AudioContextRef = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextRef) {
        return;
    }

    const context = new AudioContextRef();
    const oscillator = context.createOscillator();
    const gainNode = context.createGain();

    oscillator.type = "triangle";
    oscillator.frequency.value = frequency;
    gainNode.gain.value = 0.04;
    oscillator.connect(gainNode);
    gainNode.connect(context.destination);
    oscillator.start();
    oscillator.stop(context.currentTime + 0.1);
}

function renderScenario() {
    const scenario = modelScenarios[state.scenarioIndex];
    state.scenarioLocked = false;
    elements.scenarioTag.textContent = scenario.tag[state.language];
    elements.scenarioTitle.textContent = scenario.title[state.language];
    elements.scenarioDescription.textContent = scenario.description[state.language];
    elements.matchFeedbackText.textContent = "";
    elements.matchFeedbackStatus.textContent = t("feedback_ready");
    elements.matchAvatar.dataset.state = "ready";
    updateProgressBar(elements.matchProgressText, elements.matchProgressFill, state.scenarioIndex + 1, modelScenarios.length);
    elements.matchOptions.innerHTML = "";

    optionOrder.forEach((optionKey) => {
        const button = document.createElement("button");
        button.type = "button";
        button.className = "cg-option";
        button.textContent = t(`option_${optionKey.toLowerCase()}`);
        button.dataset.option = optionKey;
        button.addEventListener("click", () => evaluateScenario(optionKey));
        elements.matchOptions.appendChild(button);
    });
}

function evaluateScenario(optionKey) {
    if (state.scenarioLocked) {
        return;
    }

    const scenario = modelScenarios[state.scenarioIndex];
    state.scenarioLocked = true;

    const buttons = Array.from(elements.matchOptions.querySelectorAll(".cg-option"));
    buttons.forEach((button) => {
        const isCorrect = button.dataset.option === scenario.correct;
        if (isCorrect) {
            button.classList.add("is-correct");
        }
        if (button.dataset.option === optionKey && !isCorrect) {
            button.classList.add("is-wrong");
        }
        button.disabled = true;
    });

    if (optionKey === scenario.correct) {
        state.score += 12;
        state.streak += 1;
        elements.matchFeedbackText.textContent = `${t("match_correct")} ${scenario.explanation[state.language]}`;
        elements.matchFeedbackStatus.textContent = t("feedback_correct");
        elements.matchAvatar.dataset.state = "correct";
        updateScore("status_correct");
        playFeedbackTone(640);
    } else {
        state.streak = 0;
        elements.matchFeedbackText.textContent = `${t("match_wrong")} ${scenario.explanation[state.language]}`;
        elements.matchFeedbackStatus.textContent = t("feedback_retry");
        elements.matchAvatar.dataset.state = "wrong";
        updateScore("status_retry");
        playFeedbackTone(250);
    }
}

function nextScenario() {
    state.scenarioIndex = (state.scenarioIndex + 1) % modelScenarios.length;
    renderScenario();
    updateScore("status_ready");
}

function getCurrentMix() {
    return {
        h: Number(elements.sliderH.value),
        s: Number(elements.sliderS.value),
        l: Number(elements.sliderL.value)
    };
}

function hslString(colour) {
    return `hsl(${colour.h} ${colour.s}% ${colour.l}%)`;
}

function renderHueLab() {
    const target = hueTargets[state.targetIndex];
    const current = getCurrentMix();

    elements.targetSwatch.style.background = hslString(target);
    elements.currentSwatch.style.background = hslString(current);
    elements.targetMeta.textContent = `${target.name[state.language]} | H ${target.h}, S ${target.s}%, L ${target.l}%`;
    elements.currentMeta.textContent = `H ${current.h}, S ${current.s}%, L ${current.l}%`;
    elements.targetLesson.textContent = `${t("hue_lesson_prefix")}${target.lesson[state.language]}`;
    elements.sliderHValue.textContent = String(current.h);
    elements.sliderSValue.textContent = `${current.s}%`;
    elements.sliderLValue.textContent = `${current.l}%`;
    updateProgressBar(elements.hueProgressText, elements.hueProgressFill, state.targetIndex + 1, hueTargets.length);
}

function hueDistanceDegrees(a, b) {
    const direct = Math.abs(a - b);
    return Math.min(direct, 360 - direct);
}

function calculateMatchScore(current, target) {
    const hueDistance = hueDistanceDegrees(current.h, target.h) / 180;
    const saturationDistance = Math.abs(current.s - target.s) / 100;
    const lightnessDistance = Math.abs(current.l - target.l) / 100;

    const rmsDistance = Math.sqrt(
        (hueDistance ** 2 + saturationDistance ** 2 + lightnessDistance ** 2) / 3
    );

    return Math.max(0, Math.round((1 - rmsDistance) * 100));
}

function evaluateHueMatch() {
    const target = hueTargets[state.targetIndex];
    const current = getCurrentMix();
    const score = calculateMatchScore(current, target);

    elements.matchScore.textContent = `${score}%`;

    if (score >= 90) {
        state.score += 15;
        state.streak += 1;
        elements.hueFeedbackText.textContent = t("hue_perfect");
        elements.hueFeedbackStatus.textContent = t("feedback_correct");
        elements.hueAvatar.dataset.state = "correct";
        updateScore("status_correct");
        playFeedbackTone(680);
    } else if (score >= 70) {
        state.score += 8;
        state.streak += 1;
        elements.hueFeedbackText.textContent = t("hue_good");
        elements.hueFeedbackStatus.textContent = t("feedback_correct");
        elements.hueAvatar.dataset.state = "correct";
        updateScore("status_correct");
        playFeedbackTone(520);
    } else {
        state.streak = 0;
        elements.hueFeedbackText.textContent = t("hue_retry");
        elements.hueFeedbackStatus.textContent = t("feedback_retry");
        elements.hueAvatar.dataset.state = "wrong";
        updateScore("status_retry");
        playFeedbackTone(240);
    }
}

function resetHueSliders() {
    elements.sliderH.value = "180";
    elements.sliderS.value = "50";
    elements.sliderL.value = "50";
    elements.matchScore.textContent = "0%";
    elements.hueFeedbackText.textContent = "";
    elements.hueFeedbackStatus.textContent = t("feedback_ready");
    elements.hueAvatar.dataset.state = "ready";
    renderHueLab();
    updateScore("status_ready");
}

function nextHueTarget() {
    state.targetIndex = (state.targetIndex + 1) % hueTargets.length;
    resetHueSliders();
}

function attachEvents() {
    elements.chipsLanguage.forEach((button) => {
        button.addEventListener("click", () => {
            state.language = button.dataset.language;
            applyStaticTranslations();
            renderScenario();
            renderHueLab();
            updateScore("status_ready");
        });
    });

    elements.chipsFont.forEach((button) => {
        button.addEventListener("click", () => {
            const step = Number(button.dataset.fontStep);
            state.fontScale = Math.max(0.9, Math.min(1.2, state.fontScale + step * 0.05));
            document.documentElement.style.setProperty("--cg-font-scale", String(state.fontScale));
        });
    });

    elements.chipReset.addEventListener("click", () => {
        state.fontScale = 1;
        document.documentElement.style.setProperty("--cg-font-scale", "1");
    });

    elements.soundToggle.addEventListener("click", () => {
        state.soundEnabled = !state.soundEnabled;
        elements.soundToggle.textContent = state.soundEnabled ? t("sound_on") : t("sound_off");
    });

    elements.modeButtons.forEach((button) => {
        button.addEventListener("click", () => setMode(button.dataset.mode));
    });

    elements.nextScenario.addEventListener("click", nextScenario);
    elements.nextTarget.addEventListener("click", nextHueTarget);
    elements.resetHue.addEventListener("click", resetHueSliders);
    elements.checkHue.addEventListener("click", evaluateHueMatch);

    [elements.sliderH, elements.sliderS, elements.sliderL].forEach((slider) => {
        slider.addEventListener("input", renderHueLab);
    });
}

function init() {
    applyStaticTranslations();
    updateScore("status_ready");
    renderScenario();
    renderHueLab();
    attachEvents();
}

init();
