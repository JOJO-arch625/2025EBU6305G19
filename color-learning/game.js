function evaluateWorkbenchMix() {
    if (!workbenchState.running || workbenchState.canAdvance) {
        return;
    }
    const target = getCurrentRecipe();
    const current = getCurrentMix();
    const score = calculateMatchScore(current, target);

    workbenchState.totalScore += score;
    workbenchState.submissions += 1;
    workbenchState.canAdvance = workbenchState.submissions < workbenchState.targetGoal;

    if (score >= 90) {
        workbenchState.streak += 1;
        updateGlobalScore(14, "up", "status_correct");
        setWorkbenchFeedback("correct", {
            en: `Perfect mix. ${target.name.en} landed right where the brief needed it.`,
            zh: `几乎完美。${target.name.zh} 的色彩已经非常接近目标。`
        });
        playFeedbackTone(680);
    } else if (score >= 75) {
        workbenchState.streak += 1;
        updateGlobalScore(9, "up", "status_correct");
        setWorkbenchFeedback("correct", {
            en: `Good mix. A small tweak could make it even tighter, but this already works.`,
            zh: "这次已经很接近了，再微调一点会更好。"
        });
        playFeedbackTone(520);
    } else {
        workbenchState.streak = 0;
        updateGlobalScore(-1, "reset", "status_retry");
        setWorkbenchFeedback("wrong", {
            en: `Retry energy. Compare hue first, then saturation, then lightness.`,
            zh: "再试一次。先看色相，再看饱和度，最后修正明度。"
        });
        playFeedbackTone(240);
    }

    const average = Math.round(workbenchState.totalScore / workbenchState.submissions);
    if (average >= 78 && workbenchState.submissions >= workbenchState.targetGoal) {
        tasks.hueClear = true;
        updateMissionProgress();
    }

    renderWorkbench();

    if (workbenchState.submissions >= workbenchState.targetGoal) {
        finishWorkbenchRound();
    }
}

function finishWorkbenchRound() {
    stopWorkbenchRound();
    const average = workbenchState.submissions === 0 ? 0 : Math.round(workbenchState.totalScore / workbenchState.submissions);
    const rating = getRatingFromScore(average, { s: 92, a: 82, b: 70 });
    const success = average >= 78 && workbenchState.submissions >= workbenchState.targetGoal;
    if (success) {
        tasks.hueClear = true;
        updateMissionProgress();
    }
    setWorkbenchFeedback(success ? "correct" : "wrong", {
        en: success
            ? `Bench clear. You finished with a ${average}% average and a ${rating} rating.`
            : `Bench over. Your average was ${average}% with a ${rating} rating. Push it above 78% next run.`,
        zh: success
            ? `调色台完成。你的平均分是 ${average}% ，评级为 ${rating}。`
            : `本轮结束。你的平均分是 ${average}% ，评级为 ${rating}。下次尽量冲到 78% 以上。`
    });
    renderWorkbench();
}

function resetWorkbenchMix() {
    workbenchState.currentH = 180;
    workbenchState.currentS = 50;
    workbenchState.currentL = 50;
    syncWorkbenchInputs();
    renderWorkbench();
}

function movePlayer(deltaTime) {
    if (worldState.openModalKey) {
        return;
    }

    const speed = 260;
    let deltaX = 0;
    let deltaY = 0;

    if (worldState.pressedKeys.has("arrowleft") || worldState.pressedKeys.has("a")) {
        deltaX -= 1;
    }
    if (worldState.pressedKeys.has("arrowright") || worldState.pressedKeys.has("d")) {
        deltaX += 1;
    }
    if (worldState.pressedKeys.has("arrowup") || worldState.pressedKeys.has("w")) {
        deltaY -= 1;
    }
    if (worldState.pressedKeys.has("arrowdown") || worldState.pressedKeys.has("s")) {
        deltaY += 1;
    }

    if (deltaX !== 0 || deltaY !== 0) {
        const magnitude = Math.hypot(deltaX, deltaY);
        const worldWidth = elements.world.clientWidth;
        const worldHeight = elements.world.clientHeight;
        const playerWidth = 68;
        const playerHeight = 92;
        const nextX = worldState.playerX + (deltaX / magnitude) * speed * deltaTime;
        const nextY = worldState.playerY + (deltaY / magnitude) * speed * deltaTime;
        worldState.playerX = clamp(nextX, 20, worldWidth - playerWidth - 20);
        worldState.playerY = clamp(nextY, 40, worldHeight - playerHeight - 30);
        renderPlayer();
        checkNearbyStation();
    }
}

function tick(now) {
    const deltaTime = Math.min((now - worldState.lastFrameTime) / 1000, 0.032);
    worldState.lastFrameTime = now;
    movePlayer(deltaTime);
    requestAnimationFrame(tick);
}

function attachEvents() {
    elements.chipsLanguage.forEach((button) => {
        button.addEventListener("click", () => {
            worldState.language = button.dataset.language;
            applyStaticTranslations();
        });
    });

    elements.chipsFont.forEach((button) => {
        button.addEventListener("click", () => {
            const step = Number(button.dataset.fontStep);
            worldState.fontScale = clamp(worldState.fontScale + step * 0.05, 0.9, 1.2);
            document.documentElement.style.setProperty("--cg-font-scale", String(worldState.fontScale));
        });
    });

    elements.chipReset.addEventListener("click", () => {
        worldState.fontScale = 1;
        document.documentElement.style.setProperty("--cg-font-scale", "1");
    });

    elements.soundToggle.addEventListener("click", () => {
        worldState.soundEnabled = !worldState.soundEnabled;
        elements.soundToggle.textContent = worldState.soundEnabled ? t("sound_on") : t("sound_off");
    });

    document.addEventListener("keydown", (event) => {
        const key = event.key.toLowerCase();
        if (["arrowleft", "arrowright", "arrowup", "arrowdown", "w", "a", "s", "d"].includes(key)) {
            worldState.pressedKeys.add(key);
        }
        if (key === "enter" && worldState.activeStationKey) {
            interactWithStation(worldState.activeStationKey);
        }
        if (key === "escape") {
            closeModal();
            worldState.activeInfoKey = null;
            worldState.questPanelVisible = false;
            renderWorldPanels();
        }
    });

    document.addEventListener("keyup", (event) => {
        worldState.pressedKeys.delete(event.key.toLowerCase());
    });

    elements.stationButtons.forEach((button) => {
        button.addEventListener("click", () => interactWithStation(button.dataset.station));
    });

    elements.modalCloseButtons.forEach((button) => {
        button.addEventListener("click", closeModal);
    });

    elements.restartDispatch.addEventListener("click", startDispatchRound);
    elements.dispatchCook.addEventListener("click", cookDispatchOrder);
    elements.dispatchClearPrep.addEventListener("click", () => {
        dispatchState.prepModel = null;
        renderDispatchGame();
    });
    elements.restartHue.addEventListener("click", startWorkbenchRound);
    elements.checkHue.addEventListener("click", evaluateWorkbenchMix);
    elements.nextTarget.addEventListener("click", () => {
        if (workbenchState.canAdvance) {
            advanceWorkbenchTarget();
        }
    });
    elements.resetHue.addEventListener("click", resetWorkbenchMix);

    elements.sliderH.addEventListener("input", () => {
        workbenchState.currentH = Number(elements.sliderH.value);
        renderWorkbench();
    });
    elements.sliderS.addEventListener("input", () => {
        workbenchState.currentS = Number(elements.sliderS.value);
        renderWorkbench();
    });
    elements.sliderL.addEventListener("input", () => {
        workbenchState.currentL = Number(elements.sliderL.value);
        renderWorkbench();
    });

    elements.dispatchPotSlot.addEventListener("dragover", (event) => {
        event.preventDefault();
        elements.dispatchPotSlot.classList.add("is-over");
    });
    elements.dispatchPotSlot.addEventListener("dragleave", () => {
        elements.dispatchPotSlot.classList.remove("is-over");
    });
    elements.dispatchPotSlot.addEventListener("drop", (event) => {
        event.preventDefault();
        elements.dispatchPotSlot.classList.remove("is-over");
        const droppedModel = dispatchState.draggingModel || event.dataTransfer?.getData("text/plain");
        if (droppedModel) {
            setDispatchPrepModel(droppedModel);
            elements.dispatchTokenRack.querySelectorAll(".cg-model-token").forEach((node) => {
                node.classList.toggle("is-selected", node.dataset.model === droppedModel);
            });
        }
    });
}

function init() {
    applyStaticTranslations();
    renderPlayer();
    renderDispatchGame();
    renderWorkbench();
    renderWorldPanels();
    updateMissionProgress();
    checkNearbyStation();
    attachEvents();
    requestAnimationFrame(tick);
}

init();
